"""Write the detection reference (docs/detections.md) from the catalog.

    python -m sandbox.detections.docs            # rewrite docs/detections.md
    python -m sandbox.detections.docs --check    # fail if it is out of date (tests, CI)

The page is generated, never edited by hand, so it can't drift from the code: each
detection with its score, its query and the shared queries it uses, then every table and
function a query can name.
"""

from __future__ import annotations

import sys
from pathlib import Path

from sandbox.detections import catalog

OUT = Path(__file__).resolve().parents[2] / "docs" / "detections.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    from sandbox.detections.kql.tables import FUNCTIONS, TABLE_FUNCTIONS, TABLES

    dets = catalog.detections()
    areas = sorted({d.area for d in dets})
    lines = [
        "# Detections",
        "",
        "_Generated by `python -m sandbox.detections.docs` from `sandbox/detections/rules/`; "
        "do not edit by hand._",
        "",
        f"{len(dets)} detections. Each one is a rule file: a short header and a query over "
        "the capture's tables (see [detection-rules.md](detection-rules.md)). A rule fires "
        "when its query returns a row, and adds its score to the verdict (an Admin weight "
        "overrides it). Thresholds: suspicious >= 30, malicious >= 70. A feed match with "
        "confidence 75 or more on a URL, file or domain that is not allowlisted raises the "
        "score to the malicious threshold on its own (sandbox/analysis/scoring.py).",
        "",
        "Contents: "
        + ", ".join(f"[{a}](#{a})" for a in areas)
        + ", [tables](#tables), [functions](#functions).",
        "",
    ]
    for area in areas:
        lines += [
            f"## {area}",
            "",
            f"Rules: [`sandbox/detections/rules/{area}/`](../sandbox/detections/rules/{area}/)",
            "",
        ]
        for d in (d for d in dets if d.area == area):
            info = catalog.describe(d)
            lines += [
                f"### {d.title}",
                "",
                f"`{d.name}` · {d.severity} · score {d.score}"
                + (f" · ATT&CK {', '.join(d.attack)}" if d.attack else "")
                + (f" · tags {', '.join(d.tags)}" if d.tags else ""),
                "",
                d.description,
                "",
                f"Rule: [`{d.source}`](../{d.source})",
                "",
                "```kql",
                d.rule_text(),
                "```",
                "",
            ]
            for sh in info["shared"]:
                lines += [
                    "<details><summary>Uses <code>" + sh["name"] + "</code></summary>",
                    "",
                    "```kql",
                    sh["query"],
                    "```",
                    "",
                    "</details>",
                    "",
                ]
    lines += ["## Tables", "", "What the capture holds. Tables describe; rules decide.", ""]
    for name, t in {**TABLES, **TABLE_FUNCTIONS}.items():
        title = t.get("signature", name)
        lines += [
            f"### `{title}`",
            "",
            t["description"],
            "",
            "| Column | Meaning |",
            "| --- | --- |",
        ]
        lines += [f"| `{c}` | {_cell(m)} |" for c, m in t["columns"].items()]
        lines.append("")
    lines += ["## Functions", "", "| Function | Meaning |", "| --- | --- |"]
    lines += [
        f"| `{_cell(f['signature'])}` | {_cell(f['description'])} |" for f in FUNCTIONS.values()
    ]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date: run python -m sandbox.detections.docs")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
