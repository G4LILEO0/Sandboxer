"""Write the detection reference (docs/detections.md) from the catalog.

    python -m sandbox.detections.docs            # rewrite docs/detections.md
    python -m sandbox.detections.docs --check    # fail if it is out of date (tests, CI)

The page is generated, never edited by hand, so it can't drift from the code: each
detection with its score, the rule as sentences and every signal it reads.
"""

from __future__ import annotations

import sys
from pathlib import Path

from sandbox.detections import catalog
from sandbox.detections.model import SIGNALS

OUT = Path(__file__).resolve().parents[2] / "docs" / "detections.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    dets = catalog.detections()
    areas = sorted({d.area for d in dets})
    lines = [
        "# Detections",
        "",
        "_Generated by `python -m sandbox.detections.docs` from `sandbox/detections/`; "
        "do not edit by hand._",
        "",
        f"{len(dets)} detections over {len(SIGNALS)} signals. Each detection adds its "
        "score to the verdict when it fires (an Admin weight overrides it). Thresholds: "
        "suspicious >= 30, malicious >= 70. A signal never scores on its own.",
        "",
    ]
    for area in areas:
        lines += [
            f"## {area}",
            "",
            f"Code: [`sandbox/detections/{area}.py`](../sandbox/detections/{area}.py)",
            "",
        ]
        for d in (d for d in dets if d.area == area):
            lines += [
                f"### {d.title}",
                "",
                f"`{d.name}` · {d.severity} · score {d.score}"
                + (f" · ATT&CK {', '.join(d.attack)}" if d.attack else "")
                + (f" · tags {', '.join(d.tags)}" if d.tags else ""),
                "",
                d.description,
                "",
            ]
            if getattr(d, "kind", "") == "query":
                info = catalog.describe(d)
                lines += [
                    f"Rule: [`{d.source}`](../{d.source})",
                    "",
                    "```kql",
                    d.rule_text(),
                    "```",
                    "",
                ]
                for sh in info["shared"]:
                    lines += [f"Uses `{sh['name']}`:", "", "```kql", sh["query"], "```", ""]
                continue
            lines += [
                "```text",
                d.rule_text(),
                "```",
                "",
                "| Signal | How it is computed |",
                "| --- | --- |",
            ]
            tested = {t.path for t in d.when.tests()}
            for s in d.signals():
                note = "" if s.path in tested else " (evidence only)"
                lines.append(
                    f"| **{_cell(s.title)}**<br>`{s.path}`{note} | {_cell(s.description)} |"
                )
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date: run python -m sandbox.detections.docs")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
